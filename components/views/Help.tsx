export default function Help({ onStartTour }: { onStartTour: () => void }) {
  const [q, setQ] = useState('');
  const [open, setOpen] = useState<string | null>('first-run');

  const filtered = useMemo(() => {
    if (!q.trim()) return ARTICLES;
    const needle = q.trim();
    return ARTICLES.filter((a) => a.title.includes(needle) || a.tags.some((t) => t.includes(needle)) || a.body.includes(needle));
  }, [q]);

  return (
    <div className="space-y-4">
      <div className="flex flex-wrap items-center gap-2">
        <SearchBox value={q} onChange={setQ} placeholder="جستجو در راهنما (مثلاً فریز، بارکد، لایسنس)" />
        <div className="flex-1" />
        <Button onClick={onStartTour} icon={<PlayCircle size={15} />}>پخش تور آموزشی</Button>
      </div>

      <div className="grid lg:grid-cols-3 gap-4">
        <div className="lg:col-span-2 space-y-2">
          <h2 className="font-bold text-[14px] flex items-center gap-1.5"><BookOpen size={15} /> مقالات راهنما</h2>
          {filtered.map((a) => (
            <div key={a.id} className="card">
              <button className="w-full text-right px-4 py-2.5 font-semibold text-[13.5px] flex items-center justify-between" onClick={() => setOpen(open === a.id ? null : a.id)} aria-expanded={open === a.id}>
                {a.title}
                <span className="text-[11px]" style={{ color: 'var(--muted)' }}>{toPersianDigits(a.body.length)} کاراکتر</span>
              </button>
              {open === a.id ? <p className="px-4 pb-3 text-[12.5px] leading-7" style={{ color: 'var(--muted)', whiteSpace: 'pre-wrap' }}>{a.body}</p> : null}
            </div>
          ))}
          {filtered.length === 0 ? <p className="text-[13px]" style={{ color: 'var(--muted)' }}>نتیجه‌ای پیدا نشد. کلمهٔ دیگری امتحان کنید.</p> : null}
        </div>

        <div className="space-y-4">
          <div>
            <h2 className="font-bold text-[14px] mb-2 flex items-center gap-1.5"><Keyboard size={15} /> میان‌برها</h2>
            <div className="card p-2">
              <Table head={['کلید', 'کار']}>
                {SHORTCUTS.map(([k, v]) => (
                  <tr key={k}>
                    <td className="td" dir="ltr" style={{ textAlign: 'right' }}><kbd className="text-[11px] px-1.5 py-0.5 rounded" style={{ background: 'var(--edge)' }}>{k}</kbd></td>
                    <td className="td">{v}</td>
                  </tr>
                ))}
              </Table>
            </div>
          </div>

          <Section title="مجوزهای نرم‌افزاری" defaultOpen={false}>
            <Table head={['کتابخانه', 'مجوز']}>
              {THIRD_PARTY.map(([n, l]) => (
                <tr key={n}>
                  <td className="td" dir="ltr" style={{ textAlign: 'right' }}>{n}</td>
                  <td className="td">{l}</td>
                </tr>
              ))}
            </Table>
            <p className="text-[11.5px] mt-2" style={{ color: 'var(--muted)' }}>
              فونت وزیرمتن تحت مجوز SIL Open Font License 1.1 توزیع می‌شود؛ متن مجوز همراه برنامه ارائه می‌گردد.
            </p>
          </Section>

          <div className="card p-3 text-[12px] leading-7" style={{ color: 'var(--muted)' }}>
            <p className="font-bold mb-1 flex items-center gap-1.5" style={{ color: 'var(--ink)' }}><Scale size={14} /> اسناد حقوقی</p>
            <p>سیاست حریم خصوصی، قوانین استفاده و سیاست کوکی در پوشهٔ <code dir="ltr">legal/</code> پروژه نگه‌داری می‌شوند و نسخهٔ چاپی آن‌ها همراه فایل نصب ارائه می‌شود.</p>
            <p className="mt-1 flex items-center gap-1"><Info size={12} /> این راهنما آفلاین است و هیچ داده‌ای ارسال نمی‌کند.</p>
          </div>
        </div>
      </div>
    </div>
  );
}
